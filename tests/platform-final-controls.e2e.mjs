// Reusable CUA / CI regression for navigation, hidden history and immutable versions.
const assert = (condition, message) => { if (!condition) throw Error(message); };
export async function verifyFinalControls(tab, observe) {
  const ui = tab.playwright, checks = [];
  const button = name => ui.getByRole('button', { name, exact: true });
  const dialog = name => ui.getByRole('dialog', { name, exact: true });
  const click = async locator => { await locator.click(); await observe(); };
  const origin = new URL(await tab.url()).origin;
  await tab.goto(origin+'/'); await observe();
  await button('TEST UI scripted task').waitFor({ state:'visible' });
  const workbench = new URL(await tab.url());
  await click(button('TEST UI scripted task'));
  assert(new URL(await tab.url()).searchParams.get('return') === workbench.pathname+workbench.search, 'Workbench return retains the selected evaluation version');
  await click(button('返回'));
  assert(await tab.url() === workbench.href, 'Return restores the workbench and its selected evaluation version');
  checks.push('workbench_task_return_preserves_profile_version');
  await click(ui.getByRole('row').filter({ hasText:'TEST UI scripted task' }).getByRole('button', { name:'查看报告',exact:true }));
  const taskId = new URL(await tab.url()).pathname.split('/').at(-1);
  await click(button('隐藏 TEST UI scripted task'));
  await click(dialog('TEST UI scripted task').getByRole('button', { name:'确认隐藏',exact:true }));
  await click(button('查看执行历史'));
  await button('TEST UI scripted task 测试任务 测试任务').waitFor({ state:'visible' });
  checks.push('hidden_task_name_retained_in_history_filter');
  const cases = ui.getByRole('row').filter({ hasText:'TEST UI scripted case edited' });
  await ui.getByText('2 条执行尝试 · 全部历史保留', { exact:true }).waitFor({ state:'visible' });
  assert(await cases.count() === 2, 'All attempts retains the initial attempt and rerun');
  await click(button('全部尝试 全部尝试 全部尝试'));
  await click(ui.getByRole('option', { name:'当前尝试',exact:true }));
  await ui.getByText('1 条执行尝试 · 全部历史保留', { exact:true }).waitFor({ state:'visible' });
  assert(await cases.count() === 1, 'Current attempts contains one latest attempt per planned sample');
  checks.push('all_attempts_two_current_attempt_one');
  await click(button('清空筛选'));
  const cleared = new URL(await tab.url());
  assert(!cleared.searchParams.has('task_id') && !cleared.searchParams.has('all_attempts') && cleared.searchParams.has('return'), 'Clearing filters preserves the originating report');
  await click(button('返回'));
  await ui.getByRole('heading', { name:'TEST UI scripted task',exact:true }).waitFor({ state:'visible' });
  checks.push('clear_history_preserves_return_to_hidden_report');
  await click(button('隐藏资源'));
  await click(dialog('隐藏资源').getByRole('button', { name:'代码仓库 类型 类型',exact:true }));
  await click(ui.getByRole('option', { name:'测试任务',exact:true }));
  await click(dialog('隐藏资源').locator('[data-a="restore-resource"][data-resource-id="'+taskId+'"]'));
  await click(dialog('TEST UI scripted task').getByRole('button', { name:'恢复',exact:true }));
  await click(dialog('隐藏资源').getByRole('button', { name:'关闭',exact:true }));
  checks.push('hidden_task_restored_from_global_type_filter');
  for (const [nav,name] of [['测试集','TEST UI scripted dataset'],['流程画布','TEST UI scripted pipeline']]) {
    await click(ui.getByRole('link', { name:new RegExp('^'+nav) }));
    const card = ui.locator('.testflow-card').filter({ hasText:name });
    await click(card.getByRole('button', { name:'版本记录',exact:true }));
    await dialog(name+' · 版本记录').waitFor({ state:'visible' });
    await click(dialog(name+' · 版本记录').getByRole('button', { name:'关闭',exact:true }));
    checks.push(nav+'_version_badge_opens_history');
  }
  await click(ui.locator('.testflow-card').filter({ hasText:'TEST UI scripted pipeline' }).getByRole('button', { name:'打开画布',exact:true }));
  const canvas = new URL(await tab.url());
  await click(button('快速运行'));
  await click(dialog('快速运行').getByRole('button', { name:/ 评测配置 评测配置$/ }));
  await click(ui.getByRole('option', { name:'TEST UI scripted rules',exact:true }));
  await dialog('快速运行').getByRole('textbox', { name:'text',exact:true }).fill('verified quick execution return');
  await click(dialog('快速运行').getByRole('button', { name:'快速运行',exact:true }));
  await button('重跑').waitFor({ state:'visible',timeoutMs:30000 });
  const execution = new URL(await tab.url());
  assert(execution.searchParams.get('return') === canvas.pathname, 'Quick execution retains its canvas return');
  await click(ui.getByRole('tab', { name:'输入与输出',exact:true }));
  await ui.getByText('verified quick execution return', { exact:true }).first().waitFor({ state:'visible' });
  await click(button('返回'));
  assert(await tab.url() === canvas.href, 'Quick execution returns to its saved canvas');
  checks.push('real_quick_execution_returns_to_same_canvas');
  return { checks,quick_execution_id:execution.pathname.split('/').at(-1),url:await tab.url() };
}
